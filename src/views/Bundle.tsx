import React from "react";
import { formatBytes, formatSeconds } from "../build-stats";
import { readBundle } from "../project";
import { Badge, Card, Facts, HowItWorks, Icon, Loading, Meter, PageHeader, Section, useLoad } from "../ui";
import type { ViewProps } from "./meta";

function describe(name: string) {
    if (/\.html$/.test(name)) return { kind: "HTML", text: "The page that loads the rest" };
    if (/tailwind\.css$/.test(name)) return { kind: "CSS", text: "Styles generated by Tailwind, only the classes in use" };
    if (/\.css$/.test(name)) return { kind: "CSS", text: "Styles imported by the code" };
    if (/\.js$/.test(name)) return { kind: "JavaScript", text: "The project's code, React included: engine and screen" };
    if (/\.map$/.test(name)) return { kind: "Source map", text: "Links the bundle back to the source" };
    return { kind: "File", text: "" };
}

export function Bundle({ stats }: ViewProps) {
    const data = useLoad(readBundle);
    const outputs = data?.outputs || [];
    const max = Math.max(1, ...outputs.map((o) => o.bytes));
    const js = outputs.find((o) => /\.js$/.test(o.name));

    return (
        <>
            <PageHeader
                eyebrow="Bundle"
                title="Packed and ready to go."
                lead="The project packed into something this device can run: a handful of files, built right here."
            />

            <Section title="Build">
                <Facts
                    columns={3}
                    items={[
                        { label: "Entry", value: <span className="font-mono text-[13px]">index.tsx</span> },
                        { label: "Source files", value: stats.bundle.files, source: "build.json" },
                        { label: "Bundle time", value: formatSeconds(stats.bundle.seconds), source: "build.json" },
                        {
                            label: "Mode",
                            value: !data ? "…" : data.minified ? "Production, minified" : data.minified === false ? "Development" : "No bundle",
                            source: "out/"
                        },
                        {
                            label: "React build",
                            value: data?.reactBuild === "production" ? "Production" : data?.reactBuild === "development" ? "Development" : "…",
                            source: "out/"
                        },
                        { label: "Plugin", value: <span className="font-mono text-[13px]">@fullstacked/tailwindcss</span> }
                    ]}
                />
            </Section>

            <Section title="What's in out/" hint="Read from this device with fs, right now.">
                <Card className="overflow-hidden">
                    {!data ? (
                        <Loading label="Reading out/…" />
                    ) : !outputs.length ? (
                        <div className="px-4 py-6 text-[13px] text-muted">No bundle in out/ yet.</div>
                    ) : (
                        <ul className="divide-y divide-line">
                            {outputs.map((o) => {
                                const d = describe(o.name);
                                return (
                                    <li key={o.name} className="grid grid-cols-[minmax(0,1fr)_auto] items-center gap-x-4 gap-y-2 px-4 py-3 md:grid-cols-[minmax(0,1fr)_200px]">
                                        <div className="min-w-0">
                                            <div className="flex items-center gap-2">
                                                <Icon name="file" className="h-4 w-4 shrink-0 text-faint" />
                                                <span className="truncate font-mono text-[13px] font-medium">{o.name}</span>
                                                <Badge>{d.kind}</Badge>
                                            </div>
                                            <p className="mt-0.5 pl-6 text-[12.5px] leading-snug text-muted">{d.text}</p>
                                        </div>
                                        <div className="w-24 md:w-auto">
                                            <div className="mb-1.5 text-right font-mono text-[12px] tabular-nums md:text-left">{formatBytes(o.bytes)}</div>
                                            <Meter value={o.bytes} max={max} />
                                        </div>
                                    </li>
                                );
                            })}
                        </ul>
                    )}
                </Card>
                {data && data.minified === false && (
                    <p className="mt-3 flex items-start gap-2 text-[13px] text-muted">
                        <Icon name="info" className="mt-0.5 h-4 w-4 shrink-0 text-faint" />
                        <span>
                            This bundle is not minified: it was made for development, so it is readable and larger than a
                            production one.
                        </span>
                    </p>
                )}
            </Section>

            {data?.preview && (
                <Section title={`The start of out/${js?.name || "index.tsx.js"}`} hint="What this device actually runs.">
                    <Card className="relative overflow-hidden">
                        <pre className="max-h-56 overflow-hidden px-4 py-3 font-mono text-[11.5px] leading-[1.6] break-all whitespace-pre-wrap text-muted">
                            {data.preview}
                        </pre>
                        <div className="pointer-events-none absolute inset-x-0 bottom-0 h-16 bg-gradient-to-t from-raised to-transparent" />
                    </Card>
                </Section>
            )}

            {data?.html && (
                <Section title="out/index.html" hint="The only HTML: FullStacked writes it, the project has none.">
                    <Card className="overflow-hidden">
                        <pre className="scroll-area overflow-x-auto px-4 py-3 font-mono text-[12px] leading-[1.6]">{data.html.trim()}</pre>
                    </Card>
                </Section>
            )}

            <div className="space-y-3">
                <HowItWorks title="What bundling means">
                    <p>
                        A device can't run TypeScript or JSX as written, and a project spread over many files and packages
                        would load slowly. A <b>bundler</b> starts at the entry, <code>index.tsx</code>, follows every{" "}
                        <code>import</code>, turns TypeScript and JSX into plain JavaScript, and writes it all into a few files.
                    </p>
                    <p>
                        The Tailwind plugin, <code>@fullstacked/tailwindcss</code>, scans the code for class names and writes only
                        the CSS they need. FullStacked adds the small <code>index.html</code> that loads everything.
                    </p>
                </HowItWorks>
                <HowItWorks title="Why --build makes it smaller">
                    <p>
                        <code>fullstacked --build</code> makes a <b>production</b> bundle: <b>minified</b> (spaces, comments
                        and long names removed), with React's production build, which leaves out the warnings meant for
                        developers. Smaller to store, faster to start. The <i>Mode</i> above says which kind is in{" "}
                        <code>out/</code> right now.
                    </p>
                </HowItWorks>
            </div>
        </>
    );
}
